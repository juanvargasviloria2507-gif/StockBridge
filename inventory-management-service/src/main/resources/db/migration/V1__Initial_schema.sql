CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(30) NOT NULL,
    CONSTRAINT ck_users_role CHECK (role IN ('ROLE_EMPLEADO', 'ROLE_BODEGA', 'ROLE_ADMIN'))
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(80) NOT NULL UNIQUE,
    name VARCHAR(160) NOT NULL,
    category VARCHAR(100) NOT NULL,
    description VARCHAR(1000),
    price NUMERIC(12, 2) NOT NULL,
    stock INTEGER NOT NULL,
    CONSTRAINT ck_products_price CHECK (price >= 0),
    CONSTRAINT ck_products_stock CHECK (stock >= 0)
);

CREATE TABLE requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code VARCHAR(80) NOT NULL,
    requester_email VARCHAR(254) NOT NULL,
    quantity INTEGER NOT NULL,
    status VARCHAR(30) NOT NULL,
    fulfillment_source VARCHAR(30) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    estimated_delivery_days INTEGER,
    decision_reason VARCHAR(500),
    CONSTRAINT fk_requests_product_code FOREIGN KEY (product_code) REFERENCES products (code) ON DELETE RESTRICT,
    CONSTRAINT fk_requests_requester_email FOREIGN KEY (requester_email) REFERENCES users (email) ON DELETE RESTRICT,
    CONSTRAINT ck_requests_quantity CHECK (quantity > 0),
    CONSTRAINT ck_requests_status CHECK (status IN ('PENDIENTE', 'APROBADA', 'RECHAZADA', 'ENTREGADA', 'CANCELADA')),
    CONSTRAINT ck_requests_source CHECK (fulfillment_source IN ('INTERNAL', 'SUPPLIER'))
);

CREATE INDEX idx_products_category ON products (category);
CREATE INDEX idx_requests_status ON requests (status);
CREATE INDEX idx_requests_requester_email ON requests (requester_email);
CREATE INDEX idx_requests_product_code ON requests (product_code);
